   @staticmethod
   def normalize_collection_date(date_str: Optional[str]) -> str:
      """
      Normalize to YYYY-MM-DD:
         YYYY -> YYYY-01-01
         YYYY-MM -> YYYY-MM-01
         YYYY-MM-DD -> as-is
      Otherwise -> 0000-00-00
      """
      s = safe_trim(date_str)
      if not s:
         return "0000-00-00"
      if re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
         return s
      if re.fullmatch(r"\d{4}-\d{2}", s):
         return f"{s}-01"
      if re.fullmatch(r"\d{4}", s):
         return f"{s}-01-01"
      return "0000-00-00"

   
